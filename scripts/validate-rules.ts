import { writeFileSync } from 'node:fs';
import { BANK } from '../src/shared/bank';
import { buildExam } from '../src/shared/exam';
import { buildHypotheses } from '../src/shared/hypotheses';
import { simulateSolver } from '../src/shared/solver';
import { admitRate, checkBank, pickEvidence } from '../src/shared/validate';

const MAX_SURVIVORS = 5;

const errors = checkBank(BANK);
if (errors.length > 0) {
  console.error('Bank invalid:\n' + errors.map((e) => ' - ' + e).join('\n'));
  process.exit(1);
}

const H = buildHypotheses();
console.log(`hypothesis space: ${H.length} rules\n`);
console.log('rule'.padEnd(30), 'tier  cx  admit  bot  exam-survivors');

const meta: Record<string, unknown> = {};
const problems: string[] = [];

for (const e of BANK) {
  const evidence = pickEvidence(e)!;
  let solve;
  try {
    solve = simulateSolver(e.rule, [evidence.admit, evidence.reject], H);
  } catch (err) {
    problems.push(`${e.id}: ${(err as Error).message}`);
    continue;
  }
  const exam = buildExam(e.id, e.rule, H);
  if (exam.survivors > MAX_SURVIVORS) {
    problems.push(`${e.id}: exam leaves ${exam.survivors} wrong rules alive`);
  }
  const pct = (admitRate(e) * 100).toFixed(0).padStart(3);
  console.log(
    e.id.padEnd(30),
    String(e.tier).padStart(3),
    String(solve.complexity).padStart(4),
    `${pct}%`.padStart(6),
    String(solve.probes).padStart(4),
    String(exam.survivors).padStart(9)
  );
  meta[e.id] = {
    evidence,
    exam: exam.guests,
    botProbes: solve.probes,
    complexity: solve.complexity,
  };
}

if (problems.length > 0) {
  console.error('\nProblems:\n' + problems.map((p) => ' - ' + p).join('\n'));
  process.exit(1);
}

const header = '// Generated by scripts/validate-rules.ts. Do not edit.\n';
const body =
  "import type { Guest } from './types';\n\n" +
  'export interface RuleMeta {\n' +
  '  evidence: { admit: Guest; reject: Guest };\n' +
  '  exam: Guest[];\n' +
  '  /** Probes a perfect reference player needs. Humans need more. */\n' +
  '  botProbes: number;\n' +
  '  /** 1 = one test, 2 = two tests combined. */\n' +
  '  complexity: 1 | 2;\n' +
  '}\n\n' +
  'export const RULE_META: Record<string, RuleMeta> = ' +
  JSON.stringify(meta, null, 2) +
  ';\n';
writeFileSync('src/shared/bank.generated.ts', header + body);
console.log(`\nOK: ${BANK.length} rules validated, bank.generated.ts written.`);
