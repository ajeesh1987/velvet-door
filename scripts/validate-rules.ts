import { writeFileSync } from 'node:fs';
import { BANK } from '../src/shared/bank';
import { admitRate, checkBank, pickEvidence } from '../src/shared/validate';

const errors = checkBank(BANK);
if (errors.length > 0) {
  console.error('Bank invalid:\n' + errors.map((e) => ' - ' + e).join('\n'));
  process.exit(1);
}

for (const e of BANK) {
  const pct = (admitRate(e) * 100).toFixed(0);
  console.log(`${e.id.padEnd(30)} tier ${e.tier}  admits ${pct}%`);
}

const evidence = Object.fromEntries(BANK.map((e) => [e.id, pickEvidence(e)]));
const header = '// Generated by scripts/validate-rules.ts. Do not edit.\n';
const body =
  "import type { Guest } from './types';\n\n" +
  'export const EVIDENCE: Record<string, { admit: Guest; reject: Guest }> = ' +
  JSON.stringify(evidence, null, 2) +
  ';\n';
writeFileSync('src/shared/evidence.generated.ts', header + body);
console.log(`\nOK: ${BANK.length} rules, evidence written.`);
